def build_digest(
    week: str,
    stories: list[dict],
    clusters: list[list[Item]],
    feed_results: list | None = None,
    cost_usd: float | None = None,
) -> dict:
    """Join ranked stories back to their source items; sort by score.

    feed_results (fetch.FeedResult) records which sources were scanned this run.
    cost_usd, when provided, is recorded so the digest can show the run cost.
    """
    enriched = []
    for story in sorted(stories, key=lambda s: s["score"], reverse=True):
        links = [
            {"url": item.url, "source": item.source}
            for cid in story["cluster_ids"]
            for item in clusters[cid]
        ]
        enriched.append({**story, "links": links})
    digest: dict = {"week": week, "stories": enriched}
    if cost_usd is not None:
        digest["cost_usd"] = round(float(cost_usd), 4)
    if feed_results is not None:
        digest["sources_scanned"] = [
            {"name": r.name, "count": r.count, "ok": r.ok} for r in feed_results
        ]
    return digest


def render_json(digest: dict, path: Path) -> None:
    path.write_text(json.dumps(digest, indent=2) + "\n", encoding="utf-8")


def render_html(
    digest: dict,
    path: Path,
    *,
    site_url: str = DEFAULT_SITE_URL,
    cost_usd: float | None = None,
    og_image: str | None = None,
) -> None:
    week = digest["week"]
    stories = digest["stories"]
    # An explicit cost_usd (e.g. the accumulated same-week total from history)
    # wins over a stale value baked into the stored digest JSON.
    cost = cost_usd if cost_usd is not None else digest.get("cost_usd")
    sources = digest.get("sources_scanned")
    # Default og:image is this week's cover card; callers pass og_image to fall
    # back to the static site card when the per-issue card could not be written.
    image = og_image or abs_url(site_url, f"digests/{week}.png")

    desc = stories[0]["title"] if stories else TAGLINE
    page = _PAGE.format(
        week=escape(week),
        desc=escape(desc, quote=True),
        favicon=_favicon_data_uri(),
        og=og_tags(
            title=f"Sift — Week {week}",
            description=desc,
            url=abs_url(site_url, f"digests/{week}.html"),
            image=image,
            image_alt=f"Sift digest cover — Week {week}",
        ),
        style=_style(),
        theme_bootstrap=_THEME_BOOTSTRAP,
        mark=iso.mark(_PALETTE, size=54),
        range_sep=" &middot; " if week_range(week) else "",
        range=escape(week_range(week)),
        metrics=_metrics_html(len(stories), sources, cost),
        glance=_glance_html(stories),
        sections=_sections_html(stories),
        scanned=_sources_scanned_html(digest),
    )
    path.write_text(page, encoding="utf-8")


def _metrics_html(count: int, sources: list | None, cost: float | None) -> str:
    bits = [f"<b>{count}</b> stories"]
    if sources:
        live = sum(1 for s in sources if s["ok"])
        bits.append(f"<b>{live}/{len(sources)}</b> feeds live")
    if cost:
        bits.append(f"<b>${cost:.2f}</b> run")
    return " &middot; ".join(bits)


def _glance_html(stories: list[dict]) -> str:
    if not stories:
        return ""
    counts: dict[str, int] = {}
    for s in stories:
        counts[s["category"]] = counts.get(s["category"], 0) + 1
    total = sum(counts.values()) or 1
    segs, legend = [], []
    for cat, label in CATEGORY_LABELS.items():
        n = counts.get(cat, 0)
        if not n:
            continue
        pct = round(100 * n / total, 2)
        segs.append(
            f'<span data-cat="{cat}" style="width:{pct}%;background:var(--c)" '
            f'title="{escape(label)}: {n}"></span>'
        )
        legend.append(
            f'<span data-cat="{cat}">{iso.category_glyph(cat, _PALETTE)}'
            f"{escape(label)} <b>{n}</b></span>"
        )
    scores = [int(s["score"]) for s in stories]
    bars = "".join(
        f'<i data-cat="{escape(s["category"])}" style="height:{int(s["score"]) * 10}%"></i>'
        for s in stories
    )
    cap = f"hi {max(scores)} &middot; lo {min(scores)} &middot; avg {sum(scores) / len(scores):.1f}"
    return (
        '<section class="glance" aria-label="Week at a glance">\n'
        "<h2>Week at a glance</h2>\n"
        f'<div class="mixbar" role="img" aria-label="Category mix">{"".join(segs)}</div>\n'
        f'<div class="legend">{"".join(legend)}</div>\n'
        '<div class="spread">'
        f'<div class="bars" role="img" aria-label="Score spread">{bars}</div>'
        f'<p class="cap mono">{cap}</p></div>\n'
        "</section>\n"
    )


def _sections_html(stories: list[dict]) -> str:
    ranked = {id(s): i + 1 for i, s in enumerate(stories)}  # global importance rank
    sections = []
    for category, label in CATEGORY_LABELS.items():
        in_cat = [s for s in stories if s["category"] == category]
        if not in_cat:
            continue
        articles = "\n".join(_article(s, ranked[id(s)]) for s in in_cat)
        plural = "story" if len(in_cat) == 1 else "stories"
        sections.append(
            f'<h2 class="lane" data-cat="{category}">'
            f"{iso.category_glyph(category, _PALETTE)}{escape(label)}"
            f'<span class="cnt">{len(in_cat)} {plural}</span></h2>\n{articles}'
        )
    return "\n".join(sections)


def _sources_scanned_html(digest: dict) -> str:
    sources = digest.get("sources_scanned")
    if not sources:
        return ""
    items = "".join(
        f"<li>{escape(s['name'])} "
        + (
            f'<span class="cnt">{s["count"]}</span>'
            if s["ok"]
            else '<span class="cnt dead">dead</span>'
        )
        + "</li>"
        for s in sources
    )
    live = sum(1 for s in sources if s["ok"])
    return (
        '<section class="scanned">\n'
        f"<h2>Sources scanned &middot; {live}/{len(sources)} live</h2>\n"
        f'<ul class="scanned-list">{items}</ul>\n'
        "</section>"
    )


def _article(story: dict, rank: int) -> str:
    primary_url = story["links"][0]["url"] if story["links"] else "#"
    flag = '<span class="flag">needs verification</span>' if story["needs_verification"] else ""
    chips = _source_chips(story["links"])
    return (
        f'<article data-cat="{escape(story["category"])}">\n'
        f'<span class="score" title="importance {story["score"]}/10">{story["score"]}</span>\n'
        '<div class="art-body">\n'
        f'<span class="rank mono">#{rank}</span>\n'
        f'<h3><a href="{escape(safe_href(primary_url))}">{escape(story["title"])}</a>{flag}</h3>\n'
        f'<p class="summary">{escape(story["summary"])}</p>\n'
        f'<p class="rationale">{escape(story["rationale"])}</p>\n'
        f'<div class="chips">{chips}</div>\n'
        "</div>\n"
        "</article>"
    )


def _source_chips(links: list[dict]) -> str:
    """One chip per distinct source domain. A story that cites the same domain
    several times (a thread of posts, say) gets a single chip with a count,
    rather than the same chip repeated."""
    seen: dict[str, dict] = {}
    counts: dict[str, int] = {}
    for link in links:
        domain = display_domain(link["url"]) or link["source"]
        seen.setdefault(domain, link)
        counts[domain] = counts.get(domain, 0) + 1
    return "".join(_source_chip(link, counts[domain]) for domain, link in seen.items())


def _source_chip(link: dict, count: int = 1) -> str:
    # Raw domain (or feed-name fallback); escaped once at each sink below.
    domain = display_domain(link["url"]) or link["source"]
    initial = escape((domain[:1] or "?").upper())
    hue = sum(ord(c) for c in domain) % 360  # stable monogram tint
    # Lightness 33% keeps the white monogram letter ≥4.5:1 across all hues.
    tally = f' <span class="n">&times;{count}</span>' if count > 1 else ""
    return (
        f'<a class="chip" href="{escape(safe_href(link["url"]))}">'
        f'<i style="background:hsl({hue} 50% 33%)">{initial}</i>'
        f"<span>{escape(domain)}{tally}</span></a>"
    )
