"""Render the weekly digest as HTML and JSON.

The HTML is a single self-contained file (inline CSS, inline favicon, NO web
fonts or external CSS/JS) so it renders identically on the site, in email, and
offline. Visual language: a tech-brief dashboard — mono data layer, a metrics
strip, a week-at-a-glance bar + score histogram, and category lanes with
favicon-style source chips. The shareable card lives at ``digests/<week>.png``
(generated by ``site.build_site``); the head here references it as the og:image
so a pasted digest link unfurls in Teams/Slack.
"""

